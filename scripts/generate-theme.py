def render_qat(c: dict[str, str]) -> str:
    terminal = [
        c["bg_muted"], c["red"], c["green"], c["orange"], c["blue"], c["purple"], c["aqua"], c["fg"],
        c["gray"], c["red"], c["green"], c["yellow"], c["blue"], c["purple"], c["aqua"], c["fg"],
    ]
    lines = [
        "# Generated by scripts/generate-theme.py from colors.toml.",
        "edge center-sized",
        f"kitty_override background={c['bg']}",
        f"kitty_override foreground={c['fg']}",
        f"kitty_override selection_background={c['fg']}",
        f"kitty_override selection_foreground={c['bg']}",
        f"kitty_override cursor={c['gray_dim']}",
        "kitty_override cursor_text_color=background",
    ]
    lines.extend(f"kitty_override color{i}={value}" for i, value in enumerate(terminal))
    lines.extend([
        "kitty_override tab_bar_style=hidden",
        "lines 22",
        "columns 90",
        "background_opacity 0.85",
        "",
    ])
    return "\n".join(lines)


def render_waybar(c: dict[str, str]) -> str:
    names = [
        ("gb_bg", "bg"), ("gb_bg_alt", "bg_alt"), ("gb_bg_soft", "bg_soft"),
        ("gb_fg", "fg"), ("gb_gray", "gray"), ("gb_gray_dim", "gray_dim"),
        ("gb_red", "red"), ("gb_green", "green"), ("gb_yellow", "yellow"),
        ("gb_orange", "orange"), ("gb_blue", "blue"), ("gb_purple", "purple"),
        ("gb_aqua", "aqua"),
    ]
    out = ["/* Generated by scripts/generate-theme.py from colors.toml. */"]
    out.extend(f"@define-color {css} {c[key]};" for css, key in names)
    return "\n".join(out) + "\n"


def render_shell_colors(c: dict[str, str]) -> str:
    qml_names = {
        "bgHard": "bg_hard", "bg": "bg", "bgAlt": "bg_alt", "bgSoft": "bg_soft",
        "bgHover": "bg_hover", "bgMuted": "bg_muted", "fg": "fg", "fgUi": "fg_ui",
        "fgBright": "fg_bright", "fgSoft": "fg_soft", "gray": "gray", "grayDim": "gray_dim",
        "red": "red", "green": "green", "yellow": "yellow", "orange": "orange",
        "blue": "blue", "purple": "purple", "aqua": "aqua",
    }
    lines = [
        "// Generated by scripts/generate-theme.py from colors.toml. Do not edit.",
        "import QtQuick",
        "",
        "QtObject {",
    ]
    lines.extend(f'  readonly property color {name}: "{c[key]}"' for name, key in qml_names.items())
    lines.append(f'  readonly property color bgHard95: "#f5{rgb(c["bg_hard"])}"')
    lines.append("}")
    return "\n".join(lines) + "\n"


