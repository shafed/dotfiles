def generated_files(c: dict[str, str]) -> dict[Path, str]:
    return {
        ROOT / "kitty/current-theme.conf": render_kitty(c),
        ROOT / "kitty/quick-access-terminal-center.conf": render_qat(c),
        ROOT / "waybar/colors.css": render_waybar(c),
        ROOT / "hypr/colors.conf": render_hypr(c),
        ROOT / "scripts/generated-colors.sh": render_shell(c),
        ROOT / "quickshell/config/Colors.qml": render_shell_colors(c),
        ROOT / ".claude/themes/gruvbox-material.json": render_claude(c),
        ROOT / "yazi/flavors/gruvbox-dark.yazi/flavor.toml": render_yazi(c),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    files = generated_files(load_colors())
    stale: list[str] = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    if stale:
        print("stale generated theme files:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())